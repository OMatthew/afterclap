// Local checks that do not launch Chromium. Run with node review/landscape-check.cjs.
const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const current = require('../engine/plan.cjs');
function original(file) {
  const mod = { exports: {} };
  const source = execFileSync('git', ['show', 'fd89c03e4344e0e18fd576284d31a935c69391e7:engine/' + file], { cwd: root, encoding: 'utf8' });
  const req = id => id === './layout.cjs' ? original('layout.cjs') : id.startsWith('./') ? require('../engine/' + id.slice(2)) : require(id);
  vm.runInThisContext('(function(require,module,exports){' + source + '\n})', { filename: 'baseline-' + file })(req, mod, mod.exports);
  return mod.exports;
}
const old = original('plan.cjs');
const story = path.join(root, 'stories/17-thanksgiving');
const before = old.planFrom(old.loadStory(story, { writeLayout: false }));
const after = current.planFrom(current.loadStory(story, { writeLayout: false }));
const { chapters, ...comparable } = after;
assert.deepEqual(comparable, before);
console.log('PASS: portrait render plan equals HEAD (does not establish pixel equality)');
const demoDir = path.join(root, 'stories/lf-demo');
const data = current.loadStory(demoDir, { writeLayout: false });
let p = current.planFrom(data);
assert.deepEqual([p.W, p.H, p.axis, p.cap.size], [1920, 1080, 'x', 48]);
assert.equal(p.scenes[1].x0, 1920);
assert(p.camera.every(c => c.y0 === c.y1 && c.x1 > c.x0));
assert.equal(p.chapters[0].t, 0);
assert.equal(p.chapters[1].t, 13.12);
assert(p.captions.every(c => c.text.length <= 44));
const layout = data.layout();
layout.style.captions = false;
layout.scenes[1].letters = [{ text: '1927', at: 8, x: 800, y: 200 }];
layout.scenes[1].art[0].nudge = [{ at: 9, dx: 10, dy: 5 }];
p = current.planFrom({ ...data, layout });
assert(p.captions.length > 0);
assert(p.scenes[1].art.some(a => a.letters && a.left > 1920));
assert.equal(p.scenes[1].art[0].nudge[0].dx, 10);
for (const name of ['voice.mp3', 'words.json']) assert(fs.readFileSync(path.join(demoDir, name)).equals(fs.readFileSync(path.join(root, 'stories/18-macys-balloons', name))));
const { defaultLayout } = require('../engine/layout.cjs');
const defaults = defaultLayout(data.shots, data.traced, 'landscape');
assert(defaults.scenes.every(sc => sc.art.every(a => a.x >= 0 && a.x <= 1920 && a.y <= 1080)));
console.log('PASS: landscape geometry, chapters, captions, letters/nudge plan, defaults, unchanged demo audio/timestamps');
const script = fs.readFileSync(path.join(root, 'engine/page.html'), 'utf8').split('<script>')[1].split('</script>')[0];
new vm.Script(script);
console.log('PASS: page JavaScript parses');

const { writeSidecars } = require('../engine/sidecars.cjs');
const tmp = path.join(__dirname, 'sidecar-test'); fs.mkdirSync(tmp, { recursive: true });
const off = current.planFrom({ ...data, layout });
writeSidecars(off, tmp, 'test');
const srt = fs.readFileSync(path.join(tmp, 'test.srt'), 'utf8');
assert(srt.includes(off.captions[0].text));
assert(!srt.includes('00:00:24,'));
assert.equal(fs.readFileSync(path.join(tmp, 'test-chapters.txt'), 'utf8'), '0:00 The flying cat\n0:13 A reward for bringing them back\n');
writeSidecars(off, tmp, 'test', k => ({ from: '14', to: '16' })[k]);
assert.equal(fs.readFileSync(path.join(tmp, 'test-chapters.txt'), 'utf8'), '0:00 A reward for bringing them back\n');
assert(fs.readFileSync(path.join(tmp, 'test.srt'), 'utf8').includes('00:00:00,000 -->'));
writeSidecars({ ...off, chapters: [] }, tmp, 'test');
assert(!fs.existsSync(path.join(tmp, 'test-chapters.txt')));
assert.throws(() => writeSidecars(off, tmp, 'test', k => ({ from: '-1' })[k]));
fs.rmSync(tmp, { recursive: true, force: true });
console.log('PASS: SRT with captions off, clip timing, chapter formatting/ranges, stale chapter removal');
