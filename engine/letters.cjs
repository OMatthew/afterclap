const SPACE = 0.34, GAP = 0.07;

function rng(a) { return () => { a |= 0; a = (a + 0x6D2B79F5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }

// smooth curve through the points of one run (Catmull-Rom), about `step` px apart
function curve(P, step) {
  if (P.length < 3) return P.map(p => p.slice(0, 2));
  const out = [];
  for (let i = 0; i < P.length - 1; i++) {
    const p0 = P[Math.max(0, i - 1)], p1 = P[i], p2 = P[i + 1], p3 = P[Math.min(P.length - 1, i + 2)];
    const n = Math.max(1, Math.ceil(Math.hypot(p2[0] - p1[0], p2[1] - p1[1]) / step));
    for (let k = 0; k < n; k++) {
      const t = k / n, t2 = t * t, t3 = t2 * t;
      out.push([0, 1].map(c => 0.5 * (2 * p1[c] + (-p0[c] + p2[c]) * t + (2 * p0[c] - 5 * p1[c] + 4 * p2[c] - p3[c]) * t2 + (-p0[c] + 3 * p1[c] - 3 * p2[c] + p3[c]) * t3)));
    }
  }
  out.push(P[P.length - 1].slice(0, 2));
  return out;
}
// one pen stroke: smooth runs joined at its corner points
function strokePts(P, step) {
  const out = []; let run = [];
  P.forEach((p, i) => {
    run.push(p);
    if (p[2] && run.length > 1 && i < P.length - 1) { out.push(...curve(run, step).slice(0, -1)); run = [p]; }
  });
  out.push(...curve(run, step));
  return out;
}

// text -> { trace, w, h, missing }. size: height of a digit in px. The trace's box is the written text,
// origin at its top-left; `base` is the baseline's y in that box.
function lettersTrace(text, size, seed = 1, opt = {}) {
  const r = rng(seed * 2654435761 >>> 0), slant = opt.slant != null ? opt.slant : 0.07, rise = opt.rise != null ? opt.rise : 0.012;
  const strokes = [], missing = [];
  let pen = 0;
  for (const ch0 of text) {
    if (ch0 === ' ') { pen += SPACE * (0.9 + 0.2 * r()); continue; }
    const ch = G[ch0] ? ch0 : ch0.toLowerCase();
    const g = G[ch];
    if (!g) { missing.push(ch0); continue; }
    const [gw, ...ss] = g;
    // this copy of the glyph: a little bigger or smaller, tilted, sitting a hair above or below the line
    const k = 0.96 + 0.08 * r(), rot = (r() - 0.5) * 0.06, dy = (r() - 0.5) * 0.05, cx = gw / 2, cy = 0.6;
    for (const s of ss) {
      const P = s.map(p => {
        let x = (p[0] - cx) * k + (r() - 0.5) * 0.028, y = (p[1] - cy) * k + (r() - 0.5) * 0.028;
        const xr = x * Math.cos(rot) - y * Math.sin(rot), yr = x * Math.sin(rot) + y * Math.cos(rot);
        x = pen + cx + xr - slant * yr; y = cy + yr + dy - rise * (pen + cx);
        return [x * size, y * size, p[2]];
      });
      strokes.push(strokePts(P, 5));
    }
    pen += gw + GAP * (0.7 + 0.6 * r());
  }
  // box around what was written
  let x0 = 1e9, y0 = 1e9, x1 = -1e9, y1 = -1e9;
  for (const s of strokes) for (const p of s) { x0 = Math.min(x0, p[0]); y0 = Math.min(y0, p[1]); x1 = Math.max(x1, p[0]); y1 = Math.max(y1, p[1]); }
  if (!strokes.length) { x0 = y0 = 0; x1 = y1 = 1; }
  const len = s => s.reduce((a, p, i) => a + (i ? Math.hypot(p[0] - s[i - 1][0], p[1] - s[i - 1][1]) : 0), 0);
  const tr = {
    id: 'letters:' + text, write: true, size: [x1 - x0, y1 - y0], lw_src: 4, fills: [],
    strokes: strokes.map(s => { const pts = s.map(p => [+(p[0] - x0).toFixed(2), +(p[1] - y0).toFixed(2)]); return { pts, closed: false, len: +len(pts).toFixed(1), outer: true, fix: true }; }),
  };
  return { trace: tr, w: x1 - x0, h: y1 - y0, missing };
}

